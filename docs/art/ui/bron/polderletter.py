def export_bmfont(pad_png, pad_fnt, grootte, naam="Polderletter"):
    """BMFont (tekst) + PNG-atlas, wit op transparant. Godot 4 importeert .fnt als FontFile."""
    from PIL import Image
    g = GROOTTES[grootte]
    base = g["boven"] + g["cap"]           # basislijn vanaf de bovenkant van de regel
    lijn = base + g["desc"]                # regelhoogte inclusief ruimte voor accent op hoofdletters
    tekens = tekenset()
    cel_h = lijn + 2
    x, y, rijh = 1, 1, cel_h
    W = 256
    plaatsen = []
    for ch in tekens:
        if ch == " ":
            plaatsen.append((ch, None, 0, 0, 0, 0))
            continue
        m, y0 = glyph_v(ch, grootte)
        h, w = m.shape
        if x + w + 1 > W:
            x, y = 1, y + rijh
        plaatsen.append((ch, m, x, y, y0, w))
        x += w + 1
    H = y + rijh
    H = 1 << (H - 1).bit_length()
    atlas = np.zeros((H, W, 4), np.uint8)
    regels = []
    for ch, m, ax, ay, y0, w in plaatsen:
        if m is None:
            regels.append('char id=%d x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15'
                          % (ord(ch), advance(ch, grootte)))
            continue
        h = m.shape[0]
        atlas[ay:ay + h, ax:ax + w][m] = (255, 255, 255, 255)
        regels.append('char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=%d xadvance=%d page=0 chnl=15'
                      % (ord(ch), ax, ay, w, h, y0 + g["boven"], advance(ch, grootte)))
    Image.fromarray(atlas, "RGBA").save(pad_png, optimize=True)
    import os
    kop = ['info face="%s %s" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0'
           % (naam, grootte.capitalize(), lijn),
           'common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=0 greenChnl=0 blueChnl=0'
           % (lijn, base, W, H),
           'page id=0 file="%s"' % os.path.basename(pad_png),
           'chars count=%d' % len(regels)]
    with open(pad_fnt, "w", encoding="utf-8") as f:
        f.write("\n".join(kop + regels) + "\n")
    return len(regels), (W, H), lijn, base


def export_ttf(pad, grootte, naam="Polderletter"):
    """TrueType met vierkante pixels (100 eenheden per pixel). Gebruik in Godot op font_size = regelhoogte."""
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    g = GROOTTES[grootte]
    P = 100
    base = g["boven"] + g["cap"]
    lijn = base + g["desc"]
    upm = lijn * P
    tekens = tekenset()
    namen = [".notdef"] + ["u%04X" % ord(c) for c in tekens]
    cmap = {ord(c): "u%04X" % ord(c) for c in tekens}
    glyphs, metrics = {}, {}

    def leeg():
        pen = TTGlyphPen(None)
        return pen.glyph()

    pen = TTGlyphPen(None)
    for (a, b, c, d) in ((0, 0, 4, 1), (0, 0, 1, 7), (3, 0, 4, 7), (0, 6, 4, 7)):
        pen.moveTo((a * P, (b) * P)); pen.lineTo((a * P, d * P)); pen.lineTo((c * P, d * P)); pen.lineTo((c * P, b * P)); pen.closePath()
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (5 * P, 0)
    for ch in tekens:
        gn = "u%04X" % ord(ch)
        adv = advance(ch, grootte) * P
        if ch == " ":
            glyphs[gn] = leeg()
            metrics[gn] = (adv, 0)
            continue
        m, y0 = glyph_v(ch, grootte)
        pen = TTGlyphPen(None)
        h, w = m.shape
        for r in range(h):
            c = 0
            while c < w:
                if m[r, c]:
                    c2 = c
                    while c2 < w and m[r, c2]:
                        c2 += 1
                    top = (g["cap"] - (y0 + r)) * P
                    bot = top - P
                    pen.moveTo((c * P, bot)); pen.lineTo((c * P, top)); pen.lineTo((c2 * P, top)); pen.lineTo((c2 * P, bot)); pen.closePath()
                    c = c2
                else:
                    c += 1
        glyphs[gn] = pen.glyph()
        metrics[gn] = (adv, 0)
    fb = FontBuilder(upm, isTTF=True)
    fb.setupGlyphOrder(namen)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    asc, desc = (g["cap"] + g["boven"]) * P, g["desc"] * P
    fb.setupHorizontalHeader(ascent=asc, descent=-desc)
    fam = "%s %s" % (naam, grootte.capitalize())
    fb.setupNameTable({"familyName": fam, "styleName": "Regular",
                       "copyright": "Eigen werk van de studio (UI Artist, Polderlight, #87). Geen extern font.",
                       "uniqueFontIdentifier": fam + " 1.0", "fullName": fam, "version": "Version 1.000",
                       "psName": fam.replace(" ", "-")})
    fb.setupOS2(sTypoAscender=asc, sTypoDescender=-desc, sTypoLineGap=0, usWinAscent=asc, usWinDescent=desc,
                sxHeight=(g["cap"] - g["xh"]) * P, sCapHeight=g["cap"] * P, fsType=0)
    fb.setupPost()
    fb.setupHead(unitsPerEm=upm)
    fb.save(pad)
    return len(tekens)
