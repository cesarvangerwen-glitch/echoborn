G_ACC = {
    "acute": ["..#", ".#."], "grave": ["#..", ".#."], "circ": ["..#..", ".#.#."],
    "uml": None, "tilde": [".##.#", "#.##."], "ring": [".#.", "#.#"],
}

# Latin-1-letters met accent: teken -> (basis, accent)
SAMEN = {}
for basis, rij in (("A", "ÀÁÂÃÄÅ"), ("a", "àáâãäå"), ("E", "ÈÉÊË"), ("e", "èéêë"),
                   ("I", "ÌÍÎÏ"), ("i", "ìíîï"), ("O", "ÒÓÔÕÖ"), ("o", "òóôõö"),
                   ("U", "ÙÚÛÜ"), ("u", "ùúûü")):
    accenten = ["grave", "acute", "circ", "tilde", "uml", "ring"] if basis in "Aa" else \
        (["grave", "acute", "circ", "tilde", "uml"] if basis in "Oo" else ["grave", "acute", "circ", "uml"])
    for ch, acc in zip(rij, accenten):
        SAMEN[ch] = (basis, acc)
SAMEN.update({"Ñ": ("N", "tilde"), "ñ": ("n", "tilde"), "Ý": ("Y", "acute"), "ý": ("y", "acute"),
              "ÿ": ("y", "uml"), "Ç": ("C", "ced"), "ç": ("c", "ced")})
OMGEKEERD = {"¡": "!", "¿": "?"}

GROOTTES = {
    # naam: glyphs, accenten, x-hoogte-start, onderstok, spatie, regelafstand (ontwerp), boven (ruimte voor accent op hoofdletter)
    "normaal": dict(gl=N, acc=N_ACC, xh=2, cap=7, desc=2, spatie=3, regel=10, boven=2),
    "groot": dict(gl=G, acc=G_ACC, xh=3, cap=10, desc=3, spatie=4, regel=14, boven=3),
}


def _arr(rows):
    w = max(len(r) for r in rows)
    return np.array([[c == "#" for c in r.ljust(w, ".")] for r in rows], bool)


def _uml(w):
    if w <= 2:
        return ["#.#"]
    if w == 4:
        return ["#..#"]
    if w == 3:
        return ["#.#"]
    if w == 5:
        return [".#.#."]
    return ["." + "#" + "." * (w - 4) + "#" + "."]


def glyph(ch, grootte="normaal"):
    """Geeft (masker bool[h, w], y0) terug; y0 = rij t.o.v. de bovenkant van de hoofdletter."""
    g = GROOTTES[grootte]
    gl = g["gl"]
    if ch in gl:
        y0, rows = gl[ch]
        return _arr(rows), y0
    if ch in SAMEN:
        basis, acc = SAMEN[ch]
        bm, by = glyph(basis, grootte)
        if basis in "ij":  # punt weg, accent op zijn plek
            bm = bm.copy()
            bm[:g["xh"] - by] = False
        bw = bm.shape[1]
        if acc == "ced":
            am = _arr(["..#." if bw >= 4 else ".#", ".#.." if bw >= 4 else "#."]) if grootte == "normaal" \
                else _arr(["..#..", ".#..."])
            onder = by + bm.shape[0]
            ay = onder
        else:
            rows = _uml(bw) if acc == "uml" else g["acc"][acc]
            am = _arr(rows)
            if basis.isupper():
                ay = -g["boven"]          # boven de hoofdletter (normaal 2 rijen, groot 3 met 1 rij lucht)
                if acc == "uml" and grootte == "groot":
                    ay += 1
            else:
                ay = 1 if (acc == "uml" and grootte == "groot") else 0
        w = max(bw, am.shape[1])
        top = min(by, ay)
        bot = max(by + bm.shape[0], ay + am.shape[0])
        m = np.zeros((bot - top, w), bool)
        bx = (w - bw) // 2
        ax = (w - am.shape[1] + (1 if (w - am.shape[1]) % 2 and acc == "acute" else 0)) // 2
        if acc == "ced":
            ax = 0 if bw >= 4 else bx
        m[by - top:by - top + bm.shape[0], bx:bx + bw] |= bm
        m[ay - top:ay - top + am.shape[0], ax:ax + am.shape[1]] |= am
        return m, top
    return None


def tekenset():
    s = [chr(c) for c in range(0x20, 0x7F)]
    s += [c for c in "¡¿«»°·×±²³©£€…–—‘’“”"]
    s += sorted(SAMEN.keys()) + [c for c in "ÆØÐÞæøßðþ"]
    out = []
    for c in s:
        if c not in out:
            out.append(c)
    return out


def advance(ch, grootte="normaal"):
    g = GROOTTES[grootte]
    if ch == " ":
        return g["spatie"] + 1
    gm = glyph_v(ch, grootte)
    if gm is None:
        gm = glyph_v("?", grootte)
    return gm[0].shape[1] + 1


def glyph_v(ch, grootte="normaal"):
    """glyph() met de vaste plaats van ¡ en ¿ (omgekeerd, hangend op de x-hoogte)."""
    g = GROOTTES[grootte]
    if ch in OMGEKEERD:
        m, y0 = glyph(OMGEKEERD[ch], grootte)
        m = m[::-1]
        return m, g["cap"] + g["desc"] - m.shape[0]
    return glyph(ch, grootte)


def text_width(s, grootte="normaal"):
    if not s:
        return 0
    return sum(advance(c, grootte) for c in s) - 1


def draw(img, s, x, y, col, grootte="normaal", schaduw=None, schaal=1):
    """Tekent tekst; y = bovenkant van de hoofdletter. schaduw: kleur van 1 px rechtsonder."""
    if schaduw is not None:
        draw(img, s, x + schaal, y + schaal, schaduw, grootte, None, schaal)
    cx = x
    H, W = img.shape[:2]
    for ch in s:
        if ch == " ":
            cx += advance(ch, grootte) * schaal
            continue
        gm = glyph_v(ch, grootte) or glyph_v("?", grootte)
        m, y0 = gm
        if schaal != 1:
            m = np.kron(m, np.ones((schaal, schaal), bool))
        ys, xs = np.nonzero(m)
        ys = ys + y + y0 * schaal
        xs = xs + cx
        ok = (ys >= 0) & (ys < H) & (xs >= 0) & (xs < W)
        img[ys[ok], xs[ok]] = col
        cx += advance(ch, grootte) * schaal
    return cx - x


